#!/usr/bin/env python3
"""Writes docs/zones.md (every zone's long name, short name and id, by expansion) from
src/game/zone_names.inc, the client's zone table.

usage: tools/gen_zone_list.py > docs/zones.md
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# EQWorldData::ExpansionZone's numbering (docs/zones.md explains the odd ones).
EXPANSIONS = [
    "Classic", "The Ruins of Kunark", "The Scars of Velious", "The Shadows of Luclin", "The Planes of Power",
    "The Legacy of Ykesha", "Lost Dungeons of Norrath", "Gates of Discord", "Omens of War", "Dragons of Norrath",
    "Depths of Darkhollow", "Prophecy of Ro", "The Serpent's Spine", "The Buried Sea", "Secrets of Faydwer",
    "Seeds of Destruction", "Underfoot", "House of Thule", "Veil of Alaris", "Rain of Fear",
]

ROW = re.compile(r'HAILSTONE_ZONE\((\d+), "([^"]*)", "((?:[^"\\]|\\.)*)", \w+, (\d+)\)')

zones = {}
for line in open(ROOT / "src/game/zone_names.inc", encoding="utf-8"):
    m = ROW.match(line)
    if m:
        long_name = re.sub(r"\\(.)", r"\1", m.group(3))
        zones.setdefault(int(m.group(4)), []).append((long_name, m.group(2), int(m.group(1))))


def sort_key(zone):
    name = zone[0].lower()
    return (name[4:] if name.startswith("the ") else name, zone[1])


total = sum(len(z) for z in zones.values())
print("<!-- Generated by tools/gen_zone_list.py from src/game/zone_names.inc. Do not edit by hand. -->")
print()
print("# Zones by expansion")
print()
print(f"Every zone in the RoF2 client's zone table ({total} zones), with its short name (the name the server and the")
print("game folder's zone files use) and its id. Zones are grouped by the expansion the client gives each one and sorted")
print("by long name, ignoring a leading \"The\".")
print()
print("The expansion is the client's own (`EQWorldData::ExpansionZone`), not a release history, so:")
print()
print("- Classic is the default and also holds test and developer zones, housing interiors and some later remakes")
print("  (`commonlands`, `befallenb`).")
print("- Lost Dungeons of Norrath lists every adventure instance, not only the camps.")
print("- Names are spelled as the client spells them (\"BlackBurrow\", \"HighKeep\").")
print()
print("The list is regenerated with `tools/gen_zone_list.py > docs/zones.md` whenever `src/game/zone_names.inc` changes.")
print()
print("## Expansions")
print()
for e in sorted(zones):
    name = EXPANSIONS[e] if e < len(EXPANSIONS) else f"Expansion {e}"
    anchor = re.sub(r"[^a-z0-9 -]", "", f"{e} {name}".lower()).replace(" ", "-")
    print(f"- [{name}](#{anchor}) ({len(zones[e])})")
for e in sorted(zones):
    name = EXPANSIONS[e] if e < len(EXPANSIONS) else f"Expansion {e}"
    print()
    print(f"## {e} {name}")
    print()
    print("| Zone | Short name | ID |")
    print("|---|---|---|")
    for long_name, short, zone_id in sorted(zones[e], key=sort_key):
        cell = long_name.replace("|", "\\|")
        print(f"| {cell} | `{short}` | {zone_id} |")
