#!/usr/bin/env python3
"""Builds the GitHub wiki from docs/ (docs/wiki.md).

Usage: tools/sync_wiki.py --out DIR [--repo-root ROOT]
       tools/sync_wiki.py --check [--repo-root ROOT]

docs/ in this repository is the source; the wiki is its output and is never
edited by hand, so documentation still changes in the same commit as the code.
--out writes one page per document into DIR (a clone of the wiki repository,
hailstone-client.wiki.git), plus Home, _Sidebar and _Footer, and copies
docs/images/. Pages it wrote before and no longer writes are deleted; other
files in DIR are left alone. --check writes nothing and exits 1 when a
document is missing from PAGES or a markdown link points at a file that does
not exist.

What it rewrites, outside code blocks and inline code:
- markdown links to a document become links to its page (anchors kept);
- links to other files in the repository become links to them on GitHub;
- docs/<name>.md mentions in text or backticks become links to the page, and
  a quoted section name right after one ("RoF2 or live") becomes its anchor.
"""

