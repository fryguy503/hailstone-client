# Directory links (docs/protocol/) go to the section's first page.
DIR_PAGES = {
    "docs/protocol": "Protocol-Session",
    "docs/formats": "Format-WLD",
    "docs/research": "Research-External-Resources",
}

GENERATED = ("Home.md", "_Sidebar.md", "_Footer.md")
MARKER = "<!-- Generated by tools/sync_wiki.py from {src}. Edit that file, not this page. -->"

LINK = re.compile(r"(!?)\[([^\]]*)\]\(([^)\s]+)\)")
DOC_MENTION = re.compile(r"(`?)(?<![\w/.-])(docs/[A-Za-z0-9_./-]+\.md)\1(?:(\s+)\"([^\"\n]+)\")?")
INLINE_CODE = re.compile(r"(`+)(.+?)\1")


def page_map():
    return {src: page for _, pages in PAGES for src, page in pages}


def anchor(heading):
    """GitHub's anchor for a heading: lower case, punctuation dropped, spaces to hyphens."""
    text = re.sub(r"[`*_]", "", heading.strip().lower())
    text = re.sub(r"[^\w\- ]", "", text)
    return text.replace(" ", "-")


def headings(path):
    found = set()
    in_code = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.lstrip().startswith("```"):
            in_code = not in_code
        elif not in_code and line.startswith("#"):
            found.add(anchor(line.lstrip("#")))
    return found


class Converter:
    def __init__(self, root):
        self.root = root
        self.pages = page_map()
        self.anchors = {src: headings(root / src) for src in self.pages}
        self.problems = []

    def problem(self, src, msg):
        self.problems.append(f"{src}: {msg}")

    def resolve(self, src, target):
        """A link target in src -> (repo-relative path, anchor) or None when it leaves the repository."""
        if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("#"):
            return None
        path, _, frag = target.partition("#")
        base = (self.root / src).parent
        full = (base / path).resolve()
        try:
            rel = full.relative_to(self.root.resolve()).as_posix()
        except ValueError:
            return None
        return rel, frag

    def page_link(self, src, rel, frag, quoted=None):
        page = self.pages.get(rel) or DIR_PAGES.get(rel.rstrip("/"))
        if page is None:
            return None
        if quoted and not frag:
            a = anchor(quoted)
            if a in self.anchors.get(rel, set()):
                frag = a
        return page + ("#" + frag if frag else "")

    def convert_link(self, src, m):
        bang, text, target = m.groups()
        if target.startswith("#"):
            return m.group(0)
        res = self.resolve(src, target)
        if res is None:
            return m.group(0)
        rel, frag = res
        page = None if bang else self.page_link(src, rel, frag)
        if page:
            return f"[{text}]({page})"
        if not (self.root / rel).exists():
            self.problem(src, f"link to missing {target}")
            return m.group(0)
        if bang and rel.startswith("docs/images/"):
            return f"![{text}]({rel[len('docs/'):]})"
        kind = TREE if (self.root / rel).is_dir() else BLOB
        return f"{bang}[{text}]({kind}{rel}{'#' + frag if frag else ''})"

    def convert_mention(self, src, m, in_code):
        tick, rel, space, quoted = m.groups()
        if rel not in self.pages:
            # Not a document here: often another repository's path (a plugin's docs/nms.md), so it stays text.
            return m.group(0)
        page = self.page_link(src, rel, "", quoted)
        label = f"`{rel}`" if tick or in_code else rel
        tail = f'{space}"{quoted}"' if quoted else ""
        return f"[{label}]({page}){tail}"

    def convert_text(self, src, text):
        """Rewrites one span of prose (no inline code in it)."""
        out, last = [], 0
        for m in LINK.finditer(text):
            out.append(self.mentions(src, text[last:m.start()], in_code=False))
            link = self.convert_link(src, m)
            # [docs/ci.md](docs/ci.md) "MSVC under Wine": the quoted section becomes the anchor.
            q = re.match(r"\s+\"([^\"\n]+)\"", text[m.end():])
            res = None if m.group(1) else self.resolve(src, m.group(3))
            if q and res and not res[1]:
                page = self.page_link(src, res[0], "", q.group(1))
                if page and "#" in page:
                    link = f"[{m.group(2)}]({page})"
            out.append(link)
            last = m.end()
        out.append(self.mentions(src, text[last:], in_code=False))
        return "".join(out)

    def mentions(self, src, text, in_code):
        return DOC_MENTION.sub(lambda m: self.convert_mention(src, m, in_code), text)

    def convert_line(self, src, line):
        out, last = [], 0
        for m in INLINE_CODE.finditer(line):
            prose = line[last:m.start()]
            code = m.group(2)
            # A whole inline code span that is a document's path becomes a link; any other stays code.
            # A quoted section after it ("`docs/x.md` "Heading"") becomes the anchor.
            if m.group(1) == "`" and re.fullmatch(r"docs/[A-Za-z0-9_./-]+\.md", code):
                rest = line[m.end():]
                q = re.match(r"(\s+)\"([^\"\n]+)\"", rest)
                fake = DOC_MENTION.fullmatch(
                    "`" + code + "`" + (q.group(0) if q else ""))
                out.append(self.convert_text(src, prose))
                if fake:
                    out.append(self.convert_mention(src, fake, in_code=True))
                    last = m.end() + (q.end() if q else 0)
                    continue
                out.append(m.group(0))
            else:
                out.append(self.convert_text(src, prose))
                out.append(m.group(0))
            last = m.end()
        out.append(self.convert_text(src, line[last:]))
        return "".join(out)

    def convert(self, src):
        lines = (self.root / src).read_text(encoding="utf-8").splitlines()
        out, fence = [], None
        for line in lines:
            stripped = line.lstrip()
            if fence:
                out.append(line)
                if stripped.startswith(fence):
                    fence = None
                continue
            f = re.match(r"(```+|~~~+)", stripped)
            if f:
                fence = f.group(1)
                out.append(line)
                continue
            out.append(self.convert_line(src, line))
        return MARKER.format(src=src) + "\n\n" + "\n".join(out) + "\n"


def title(root, src):
    for line in (root / src).read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return src


def home(root):
    lines = [MARKER.format(src="tools/sync_wiki.py"), "",
             "# Hailstone documentation", "",
             f"Hailstone is a portable client for EQEmu servers ([repository]({REPO_URL}), "
             f"[README]({BLOB}README.md), [changelog]({BLOB}CHANGELOG.md), "
             f"[releases]({REPO_URL}/releases)).", "",
             "Hailstone ships no game files: it reads a RoF2 or current live EverQuest installation, Daybreak "
             "Game Company's work. If you play on those files, we highly encourage you to subscribe to "
             "[EverQuest](https://www.everquest.com) and support the game. Hailstone is not affiliated with or "
             "endorsed by Daybreak Game Company.", "",
             "These pages are built from the repository's `docs/` folder by `tools/sync_wiki.py`. "
             "To change one, edit its file in the repository and send a pull request; "
             "edits made here are overwritten.", ""]
    for section, pages in PAGES:
        lines += [f"## {section}", ""]
        lines += [f"- [{title(root, src)}]({page})" for src, page in pages]
        lines.append("")
    return "\n".join(lines)


def sidebar():
    lines = [MARKER.format(src="tools/sync_wiki.py"), "", "**[Home](Home)**", ""]
    for section, pages in PAGES:
        lines += [f"**{section}**", ""]
        lines += [f"- [{page.replace('-', ' ')}]({page})" for _, page in pages]
        lines.append("")
    return "\n".join(lines)


def footer():
    return (f"Built from [`docs/`]({TREE}docs) by `tools/sync_wiki.py`. "
            f"Edit the source in the [repository]({REPO_URL}), not this page.\n")


def missing_pages(root):
    listed = set(page_map())
    on_disk = {p.relative_to(root).as_posix() for p in (root / "docs").rglob("*.md")}
    return sorted(on_disk - listed), sorted(s for s in listed if not (root / s).exists())


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parent.parent)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--out", type=Path, help="the wiki checkout to write into")
    mode.add_argument("--check", action="store_true", help="report problems, write nothing")
    args = ap.parse_args()
    root = args.repo_root.resolve()

    unlisted, gone = missing_pages(root)
    problems = [f"{s}: not in PAGES (tools/sync_wiki.py)" for s in unlisted]
    problems += [f"{s}: in PAGES but missing" for s in gone]
    if gone:
        print("\n".join(problems), file=sys.stderr)
        return 1

    conv = Converter(root)
    pages = {page + ".md": conv.convert(src) for src, page in page_map().items()}
    pages["Home.md"] = home(root)
    pages["_Sidebar.md"] = sidebar()
    pages["_Footer.md"] = footer()
    problems += conv.problems

    if args.check:
        for p in problems:
            print(p, file=sys.stderr)
        return 1 if problems else 0

    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    # Delete pages this script wrote before that it no longer writes (a document renamed or removed).
    for old in out.glob("*.md"):
        if old.name not in pages and "Generated by tools/sync_wiki.py" in old.read_text(encoding="utf-8"):
            old.unlink()
    for name, text in pages.items():
        (out / name).write_text(text, encoding="utf-8", newline="\n")
    images = root / "docs" / "images"
    if images.is_dir():
        shutil.copytree(images, out / "images", dirs_exist_ok=True)
    for p in problems:
        print("warning:", p, file=sys.stderr)
    print(f"wrote {len(pages)} pages to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
